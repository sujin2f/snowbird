/**
 * Enqueue compiled theme scripts into the Block Editor.
 */
function my_block_theme_editor_assets() {
    // Automatically load dependencies generated by wp-scripts (like wp-blocks, wp-element)
    $asset_file = include get_template_directory() . '/build/index.asset.php';

    wp_enqueue_script(
        'my-theme-editor-script',
        get_template_directory_uri() . '/build/index.js',
        $asset_file['dependencies'],
        $asset_file['version'],
        true
    );
}
add_action( 'enqueue_block_editor_assets', 'my_block_theme_editor_assets' );

add_action('after_setup_theme', function() {
    if ( ! is_admin() ) {
        return;
    }

    $styles = array(
        'assets/css/button.css',
        'assets/css/header.css',
        'assets/css/footer.css',
    );
    // Enqueues a specific stylesheet into the block editor canvas
    add_editor_style( $styles );
});

function my_theme_remove_layout_styles() {
    // Remove default block editor layout styles
    add_theme_support( 'disable-layout-styles' );
}
add_action( 'after_setup_theme', 'my_theme_remove_layout_styles' );

remove_action('wp_enqueue_scripts', 'wp_enqueue_global_styles');
remove_action('wp_footer', 'wp_enqueue_global_styles', 1);
