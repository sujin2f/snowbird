<?php
add_action('after_setup_theme', function() {
    add_theme_support('wp-block-styles');
    add_theme_support('responsive-embeds');
    add_theme_support('editor-styles');
});

add_action('init', function() {
    register_block_pattern_category('my-theme', [
        'label' => 'My Theme',
    ]);
});

add_action('wp_enqueue_scripts', function() {
    wp_enqueue_script(
        'index-js', // Unique handle
        get_stylesheet_directory_uri() . '/build/index.js', 
        array('wp-blocks', 'wp-dom-ready'), // Dependencies (if any)
        '4.4.3', // Version number
        true // Load in footer
    );

    wp_enqueue_style(
        'style', // Unique handle for your stylesheet
        get_stylesheet_uri(), 
        array(), // Dependencies (leave empty array if none)
        '0.0.8', // Version number (helps with cache busting)
        'all' // Media type (e.g., 'all', 'print', 'screen')
    );

    wp_enqueue_style(
        'font-cdn', // Unique handle for your stylesheet
        'https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.1/css/all.min.css', // Full URL to the CDN file
        array(), // Dependencies (leave empty array if none)
        '1.0.0', // Version number (helps with cache busting)
        'all' // Media type (e.g., 'all', 'print', 'screen')
    );
});

